import { AREAS } from './areas.ts';
import { OCCUPATIONS } from './occupations.ts';

/** The OEWS data types the pages carry: the hourly mean wage (03) and the hourly median wage (08). */
const DATA_TYPES = { mean: '03', median: '08' } as const;
export type Kind = keyof typeof DATA_TYPES;

/** A measured value of a series: dollars per hour. */
export type Reading = number;

/**
 * The BLS series id of an OEWS estimate: `OE`, seasonality `U`, area type (`S` state, `N` national),
 * a 7-digit area (state FIPS and `00000`), a 6-digit industry (`000000`, all industries), the 6-digit
 * SOC code and the 2-digit data type. `US` is the national estimate.
 */
export const seriesIdOf = (area: string, soc: string, kind: Kind): string =>
  area === 'US'
    ? `OEUN${'0'.repeat(13)}${soc}${DATA_TYPES[kind]}`
    : `OEUS${area}00000${'0'.repeat(6)}${soc}${DATA_TYPES[kind]}`;

/**
 * The source of `oews-2025.ts` from the readings of one fetch: per occupation, the national
 * `[mean, median]` and each state's, in FIPS order. An area with only one of the two is left out
 * (a page needs both), and an occupation with no reading stays an empty record.
 */
export const wagesModule = (readings: ReadonlyMap<string, Reading>): string => {
  const pairOf = (area: string, soc: string): string | undefined => {
    const mean = readings.get(seriesIdOf(area, soc, 'mean'));
    const median = readings.get(seriesIdOf(area, soc, 'median'));
    return mean === undefined || median === undefined
      ? undefined
      : `[${String(mean)}, ${String(median)}]`;
  };
  const occupations = OCCUPATIONS.map(({ id, soc }) => {
    const rows = [
      ['US', pairOf('US', soc)],
      ...AREAS.map(({ fips }) => [`'${fips}'`, pairOf(fips, soc)] as const),
    ].flatMap(([key, pair]) => (pair === undefined ? [] : [`    ${String(key)}: ${pair},\n`]));
    return rows.length === 0 ? `  ${id}: {},\n` : `  ${id}: {\n${rows.join('')}  },\n`;
  });
  return `// Generated by scripts/fetch-wages.ts from the BLS Public Data API: do not edit by hand.
// Numbers only: hourly mean and median wage in dollars, by occupation and state (FIPS code).

/** U.S. Bureau of Labor Statistics, Occupational Employment and Wage Statistics: \`[mean, median]\`. */
export type Wage = readonly [mean: number, median: number];

export const OEWS_RELEASE = {
  release: 'May 2025',
  accessed: '2026-11-08',
} as const;

export const OEWS: Readonly<Record<string, Readonly<Record<string, Wage>>>> = {
${occupations.join('')}};
`;
};

/**
 * Pure parts of the USDA zone build (`build-zones.ts` does the I/O): reading the PRISM grid of the
 * 2023 USDA Plant Hardiness Zone Map, the value at a station, and the generated modules.
 */
import { inflateRawSync } from 'node:zlib';
import { zoneOf, type StationZone } from '../src/zones/zone.ts';

/** The geometry of a BIL grid: `ulx`/`uly` are the center of the upper-left cell, in degrees. */
export interface GridHeader {
  readonly rows: number;
  readonly cols: number;
  readonly ulx: number;
  readonly uly: number;
  readonly dx: number;
  readonly dy: number;
  readonly nodata: number;
}

/** A grid of little-endian 32-bit floats, row by row from the north-west corner. */
export interface Grid {
  readonly header: GridHeader;
  readonly data: Buffer;
}

/** Reads an ESRI `.hdr`; only one band of little-endian 32-bit floats is accepted. */
export function parseBilHeader(text: string): GridHeader {
  const fields = new Map(
    text
      .split(/\r?\n/)
      .map((line) => line.trim().split(/\s+/))
      .filter((parts): parts is [string, string] => parts.length === 2)
      .map(([key, value]) => [key.toUpperCase(), value]),
  );
  const expect = (key: string, value: string): void => {
    if (fields.get(key) !== value) throw new Error(`grid header: ${key} must be ${value}`);
  };
  expect('BYTEORDER', 'I');
  expect('NBITS', '32');
  expect('NBANDS', '1');
  expect('PIXELTYPE', 'FLOAT');
  const number = (key: string): number => {
    const value = Number(fields.get(key));
    if (!fields.has(key) || !Number.isFinite(value)) throw new Error(`grid header: no ${key}`);
    return value;
  };
  return {
    rows: number('NROWS'),
    cols: number('NCOLS'),
    ulx: number('ULXMAP'),
    uly: number('ULYMAP'),
    dx: number('XDIM'),
    dy: number('YDIM'),
    nodata: number('NODATA'),
  };
}

/** The value of the cell whose center is nearest (`lat`, `lon`), or `null` off the grid or no data. */
export function gridValue({ header, data }: Grid, lat: number, lon: number): number | null {
  const col = Math.round((lon - header.ulx) / header.dx);
  const row = Math.round((header.uly - lat) / header.dy);
  if (col < 0 || col >= header.cols || row < 0 || row >= header.rows) return null;
  const value = data.readFloatLE((row * header.cols + col) * 4);
  return value === header.nodata ? null : value;
}

/** The zone of a raw grid value and the value to a tenth of a degree (`+ 0` turns -0 into 0). */
export function stationZoneOf(value: number): StationZone {
  return [zoneOf(value).label, Math.round(value * 10) / 10 + 0];
}

/** The file `name` of a zip, found through its central directory, stored or deflated. */
export function zipEntry(zip: Buffer, name: string): Buffer {
  const end = zip.lastIndexOf(Buffer.from([0x50, 0x4b, 0x05, 0x06]));
  if (end < 0) throw new Error('not a zip');
  const count = zip.readUInt16LE(end + 10);
  let at = zip.readUInt32LE(end + 16);
  for (let index = 0; index < count; index += 1) {
    const nameLength = zip.readUInt16LE(at + 28);
    const extra = zip.readUInt16LE(at + 30);
    const comment = zip.readUInt16LE(at + 32);
    if (zip.toString('utf8', at + 46, at + 46 + nameLength) === name) {
      const method = zip.readUInt16LE(at + 10);
      const size = zip.readUInt32LE(at + 20);
      const local = zip.readUInt32LE(at + 42);
      const start = local + 30 + zip.readUInt16LE(local + 26) + zip.readUInt16LE(local + 28);
      const body = zip.subarray(start, start + size);
      if (method === 0) return body;
      if (method === 8) return inflateRawSync(body);
      throw new Error(`${name}: unsupported zip method ${String(method)}`);
    }
    at += 46 + nameLength + extra + comment;
  }
  throw new Error(`${name} is not in the zip`);
}

export interface ZoneRow {
  readonly id: string;
  readonly zone: string;
  readonly min: number;
}

const HEADER = '// Generated by packages/lawn-data/scripts/build-zones.ts: do not edit.\n';

/** `src/zones/stations.ts`: the zone of every station, sorted by id. */
export function renderZonesModule(rows: readonly ZoneRow[]): string {
  const lines = rows
    .toSorted((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
    .map(({ id, zone, min }) => `  ${id}: ['${zone}', ${String(min)}],`);
  return `${HEADER}
import type { StationZone } from './zone.ts';

/** The USDA half zone and average annual extreme minimum (°F) of each contiguous-US station. */
export const STATION_ZONES: Readonly<Record<string, StationZone>> = {
${lines.join('\n')}
};
`;
}

const PHZM = 'https://prism.oregonstate.edu/phzm';

/** `src/zones/source.ts`: what the zones are read from, and the day the grid was pulled. */
export function renderZoneSourceModule(pulled: string): string {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(pulled)) {
    throw new RangeError(`pulled must be YYYY-MM-DD: ${pulled}`);
  }
  return `${HEADER}
export const ZONE_SOURCE = {
  pulled: '${pulled}',
  map: {
    name: 'USDA Agricultural Research Service, 2023 USDA Plant Hardiness Zone Map',
    url: 'https://planthardiness.ars.usda.gov/',
  },
  grid: {
    name: 'PRISM Climate Group, Oregon State University: 1991-2020 mean annual extreme minimum temperature, conterminous US (phzm_us_grid_2023)',
    pageUrl: '${PHZM}/',
    dataUrl: '${PHZM}/data/2023/phzm_us_grid_2023.zip',
  },
  terms:
    'Under the terms of a Specific Cooperative Agreement between the US Department of Agriculture and Oregon State University (OSU), OSU retains ownership of the GIS datasets underlying the official 2023 USDA Plant Hardiness Zone Map. These datasets may be freely reproduced and redistributed (phzm_terms_of_use.txt).',
  method:
    'Each NOAA station of the 48 contiguous states takes the value of the 30-arc-second grid cell whose center is nearest its coordinates; the half zone is that value in 5°F steps from -60°F.',
} as const;
`;
}
